/**
 * Assemble the QG-03b conformance extensions.
 *
 *   node artifacts/experiments/W1-QG03b-letterbox-conformance/harness/build-qg03b-extension.mjs
 *
 * Prerequisites, neither of which this script works around:
 *   npm run typecheck                        compiles packages/{perception,security}
 *   python tools/detector/qg03b_fixtures.py  generates the fixtures and Python digests
 *
 * The shipped compiled packages go in VERBATIM — no bundler. The module under test must be
 * the module that ships, or the conformance result describes something else.
 *
 * The detector artifact and the QG-03 reference boxes are inlined when present, so the
 * "same PNG, same detections?" question can be answered in the same run. They are optional:
 * the conformance measurement itself needs no model.
 */
import { copyFileSync, cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..", "..", "..", "..");
const EXP = join(HERE, "..");
const GEN = join(HERE, "generated");
const ORT_DIST = join(ROOT, "node_modules", "onnxruntime-web", "dist");
const OUT_CHROME = join(HERE, "ext-chrome");
const OUT_FIREFOX = join(HERE, "ext-firefox");
const PORT = 8914;

function must(p, hint) {
  if (!existsSync(p)) {
    console.error(`missing: ${p}\n  ${hint}`);
    process.exit(1);
  }
  return p;
}

must(join(ROOT, "packages/perception/dist/src/index.js"), "run: npm run typecheck");
must(join(ROOT, "packages/security/dist/src/index.js"), "run: npm run typecheck");
must(join(EXP, "fixtures.json"), "run: python tools/detector/qg03b_fixtures.py");

const fixtures = JSON.parse(readFileSync(join(EXP, "fixtures.json"), "utf8"));
const { buildExtensionPagesCsp } = await import(pathToFileURL(join(ROOT, "packages/security/dist/src/index.js")).href);
const CSP = buildExtensionPagesCsp(`http://127.0.0.1:${PORT}`);

// QG-03's reference gives the CSS boxes the Python path produces for the real frames.
// Without it the conformance measurement still runs; only the detection comparison drops.
const QG03_REF = join(ROOT, "artifacts/experiments/W1-QG03-t1-detector-runtime/reference-summary.json");
const refBoxes = new Map();
if (existsSync(QG03_REF)) {
  const r = JSON.parse(readFileSync(QG03_REF, "utf8"));
  for (const c of r.cases) {
    if (!c.sampleId) continue;
    refBoxes.set(c.sampleId, { boxes: c.shippedDecode.cssBoxes, geometry: c.geometry });
  }
}

const payload = { fixtures: [], png: {}, model: null };
for (const f of fixtures.fixtures) {
  const png = join(GEN, `${f.name}.png`);
  if (!existsSync(png)) continue;
  const entry = {
    name: f.name,
    source: f.source,
    geometry: f.geometry,
    digests: f.digests,
    sampleId: f.sampleId ?? null,
  };
  const ref = f.sampleId ? refBoxes.get(f.sampleId) : null;
  if (ref) {
    entry.referenceBoxes = ref.boxes;
    entry.geometryCss = { capture: ref.geometry.capture, viewportCss: ref.geometry.viewportCss };
  }
  payload.fixtures.push(entry);
  payload.png[f.name] = readFileSync(png).toString("base64");
}

const modelPath = join(ROOT, "artifacts/models/t1-ui-head/t1-ui-head.onnx");
const cardPath = join(ROOT, "artifacts/models/t1-ui-head/model-card.json");
if (existsSync(modelPath) && existsSync(cardPath)) {
  const card = JSON.parse(readFileSync(cardPath, "utf8"));
  payload.model = {
    modelId: card.modelId,
    revision: card.revision,
    sha256: card.artifact.sha256,
    bytes: card.artifact.bytes,
    b64: readFileSync(modelPath).toString("base64"),
  };
}

const ORT_FILES = [
  "ort.all.min.js",
  "ort-wasm-simd-threaded.mjs",
  "ort-wasm-simd-threaded.wasm",
  "ort-wasm-simd-threaded.jsep.mjs",
  "ort-wasm-simd-threaded.jsep.wasm",
];

for (const out of [OUT_CHROME, OUT_FIREFOX]) {
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  if (payload.model) for (const f of ORT_FILES) copyFileSync(must(join(ORT_DIST, f), "npm install"), join(out, f));
  cpSync(join(ROOT, "packages/perception/dist/src"), join(out, "perception"), { recursive: true });
  cpSync(join(ROOT, "packages/security/dist/src"), join(out, "security"), { recursive: true });
  copyFileSync(join(HERE, "qg03b-probe.js"), join(out, "qg03b-probe.js"));
  writeFileSync(
    join(out, "qg03b-fixtures.js"),
    `// GENERATED by build-qg03b-extension.mjs — do not edit.\nglobalThis.QG03B_FIXTURES = ${JSON.stringify(payload)};\n`
  );
  for (const sub of ["perception", "security", "security/generated"]) {
    const d = join(out, sub);
    if (!existsSync(d)) continue;
    for (const f of readdirSync(d)) if (f.endsWith(".d.ts")) rmSync(join(d, f));
  }
}

const ortTags = payload.model ? '<script src="ort.all.min.js"></script>' : "";

writeFileSync(
  join(OUT_CHROME, "manifest.json"),
  JSON.stringify(
    {
      manifest_version: 3,
      name: "PratiBimb QG-03b preprocessing conformance (Chrome)",
      version: "1.0.0",
      description: "Throwaway harness. Compares browser preprocessing against the Python reference, stage by stage.",
      minimum_chrome_version: "116",
      background: { service_worker: "background.js" },
      permissions: ["offscreen"],
      host_permissions: [`http://127.0.0.1:${PORT}/*`],
      content_security_policy: { extension_pages: CSP },
    },
    null,
    2
  )
);

writeFileSync(
  join(OUT_CHROME, "offscreen.html"),
  '<!doctype html><html><head><meta charset="utf-8"><title>qg03b</title>' +
    ortTags +
    '<script src="qg03b-fixtures.js"></script><script src="qg03b-probe.js"></script><script src="offscreen.js"></script>' +
    "</head><body></body></html>"
);

writeFileSync(
  join(OUT_CHROME, "offscreen.js"),
  [
    'chrome.runtime.onMessage.addListener((msg) => {',
    '  if (!msg || msg.type !== "qg03b-go") return;',
    "  (async () => {",
    '    const base = chrome.runtime.getURL("");',
    "    let r;",
    "    try {",
    '      r = await globalThis.runQg03bProbe("chrome-offscreen-document", Object.assign({ base: base }, msg.config));',
    "    } catch (e) {",
    '      r = { context: "chrome-offscreen-document", conclusion: "probe threw", error: { message: String((e && e.message) || e).slice(0, 400) } };',
    "    }",
    '    chrome.runtime.sendMessage({ type: "qg03b-result", result: r });',
    "  })();",
    "});",
  ].join("\n")
);

writeFileSync(
  join(OUT_CHROME, "background.js"),
  [
    `const BASE = "http://127.0.0.1:${PORT}";`,
    "async function ensureOffscreen() {",
    '  const has = await chrome.runtime.getContexts({ contextTypes: ["OFFSCREEN_DOCUMENT"] });',
    "  if (has.length) return;",
    '  await chrome.offscreen.createDocument({ url: "offscreen.html", reasons: ["WORKERS"], justification: "QG-03b conformance" });',
    "}",
    "globalThis.__qg03b_run = async function (config) {",
    "  await ensureOffscreen();",
    "  const r = await new Promise((resolve) => {",
    '    const t = setTimeout(() => resolve({ context: "chrome-offscreen-document", conclusion: "offscreen timeout" }), 300000);',
    "    chrome.runtime.onMessage.addListener(function h(m) {",
    '      if (m && m.type === "qg03b-result") { clearTimeout(t); chrome.runtime.onMessage.removeListener(h); resolve(m.result); }',
    "    });",
    '    chrome.runtime.sendMessage({ type: "qg03b-go", config: config }).catch(() => {});',
    "  });",
    '  try { await fetch(BASE + "/result", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ contexts: [r] }) }); } catch (e) {}',
    "  return r;",
    "};",
  ].join("\n")
);

writeFileSync(
  join(OUT_FIREFOX, "manifest.json"),
  JSON.stringify(
    {
      manifest_version: 3,
      name: "PratiBimb QG-03b preprocessing conformance (Firefox)",
      version: "1.0.0",
      description: "Throwaway harness. Compares browser preprocessing against the Python reference, stage by stage.",
      browser_specific_settings: { gecko: { id: "pratibimb-qg03b@example.invalid", strict_min_version: "128.0" } },
      background: {
        scripts: [
          ...(payload.model ? ["ort.all.min.js"] : []),
          "qg03b-fixtures.js",
          "qg03b-probe.js",
          "ff-background.js",
        ],
      },
      permissions: ["tabs"],
      host_permissions: [`http://127.0.0.1:${PORT}/*`],
      content_security_policy: { extension_pages: CSP },
    },
    null,
    2
  )
);

writeFileSync(
  join(OUT_FIREFOX, "ff-background.js"),
  [
    'const api = typeof browser !== "undefined" ? browser : chrome;',
    `const BASE = "http://127.0.0.1:${PORT}";`,
    "const CONFIG = __CONFIG__;",
    "function beacon(q) { try { return api.tabs.create({ url: BASE + q, active: false }); } catch (e) { return Promise.resolve(); } }",
    "async function deliver(payload) {",
    "  const body = JSON.stringify(payload);",
    "  try {",
    '    const res = await fetch(BASE + "/result", { method: "POST", headers: { "content-type": "application/json" }, body: body });',
    "    if (res && res.ok) return;",
    "  } catch (e) {}",
    "  const enc = encodeURIComponent(body);",
    "  const CH = 6000;",
    "  const n = Math.ceil(enc.length / CH);",
    '  const id = "qg03b-" + Date.now();',
    '  for (let i = 0; i < n; i++) await beacon("/chunk?id=" + id + "&i=" + i + "&n=" + n + "&d=" + enc.slice(i * CH, (i + 1) * CH));',
    "}",
    "(async () => {",
    '  await beacon("/alive?stage=start");',
    '  const base = api.runtime.getURL("");',
    "  let r;",
    "  try {",
    '    r = await globalThis.runQg03bProbe("firefox-mv3-event-page", Object.assign({ base: base }, CONFIG));',
    "  } catch (e) {",
    '    r = { context: "firefox-mv3-event-page", conclusion: "probe threw", error: { message: String((e && e.message) || e).slice(0, 400) } };',
    "  }",
    "  await deliver({ contexts: [r] });",
    "})();",
  ].join("\n")
);

console.log("built ext-chrome and ext-firefox");
console.log(`  CSP: ${CSP}`);
console.log(`  fixtures inlined: ${payload.fixtures.length} (${payload.fixtures.filter((f) => f.referenceBoxes).length} with reference boxes)`);
console.log(`  model: ${payload.model ? `${payload.model.bytes} bytes, ${payload.model.revision}` : "ABSENT — detection comparison will be skipped"}`);
