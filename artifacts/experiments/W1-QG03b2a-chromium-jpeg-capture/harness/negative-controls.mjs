/**
 * Prove the harness can fail.
 *
 *   CHROME_PATH=... node artifacts/experiments/W1-QG03b2a-chromium-jpeg-capture/harness/negative-controls.mjs
 *
 * A conformance run that reports 40/40 is worth exactly as much as the evidence that it
 * would have reported something else had something been wrong. Each control below breaks
 * ONE thing in the built extension, runs the real probe against it, and requires the
 * specific guard that owns that failure to fire — not merely "something went red".
 *
 *   1. CORRUPTED BYTES       flip one byte of a captured JPEG. The in-browser SHA-256 check
 *                            must notice that the two sides no longer hold the same file.
 *   2. MISLABELLED TYPE      claim a PNG capture is a JPEG. The magic-byte check must catch
 *                            the bytes and the label disagreeing.
 *   3. SWAPPED REFERENCE     point a fixture at another fixture's reference dump. The pixel
 *                            comparison must report a difference instead of passing.
 *
 * Control 3 matters most. Controls 1 and 2 test the integrity checks; only 3 tests the
 * measurement itself, and a measurement that cannot report a difference is decoration.
 *
 * This runs on demand, not in CI: it needs a browser, a built extension, and several
 * minutes. Its OUTPUT is committed and a permanent test asserts that output stays correct.
 */
import { createServer } from "node:http";
import { copyFileSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";

const HERE = dirname(fileURLToPath(import.meta.url));
const EXT = join(HERE, "ext-chrome");
const FIXTURES_JS = join(EXT, "qg03b2a-fixtures.js");
const BACKUP = join(HERE, "..", "logs", ".fixtures-backup.js");
const PORT = 8932;
const CHROME = process.env.CHROME_PATH;

if (!CHROME) {
  console.error("CHROME_PATH must point at an unbranded Chromium.");
  process.exit(1);
}

const PREFIX = "// GENERATED by build-qg03b2a-extension.mjs — do not edit.\nglobalThis.QG03B2A_FIXTURES = ";
function readPayload() {
  const src = readFileSync(FIXTURES_JS, "utf8");
  return JSON.parse(src.slice(src.indexOf("= ") + 2, src.lastIndexOf(";")));
}
function writePayload(p) {
  writeFileSync(FIXTURES_JS, `${PREFIX}${JSON.stringify(p)};\n`);
}

function startCollector() {
  const server = createServer((req, res) => {
    if (req.method === "POST" && req.url === "/result") {
      req.on("data", () => {});
      req.on("end", () => {
        res.writeHead(200, { "content-type": "application/json" });
        res.end("{}");
      });
      return;
    }
    res.writeHead(404);
    res.end();
  });
  return new Promise((r) => server.listen(PORT, "127.0.0.1", () => r(server)));
}

async function runProbe() {
  const udd = mkdtempSync(join(tmpdir(), "pratibimb-qg03b2a-neg-"));
  let ctx;
  try {
    ctx = await chromium.launchPersistentContext(udd, {
      headless: true,
      executablePath: CHROME,
      args: [`--disable-extensions-except=${EXT}`, `--load-extension=${EXT}`, "--no-sandbox"],
    });
    const sw = ctx.serviceWorkers()[0] || (await ctx.waitForEvent("serviceworker", { timeout: 60000 }));
    return await sw.evaluate((c) => globalThis.__qg03b2a_run(c), { backend: "wasm" });
  } finally {
    try {
      await ctx?.close();
    } catch {
      /* disposable */
    }
    try {
      rmSync(udd, { recursive: true, force: true });
    } catch {
      /* Windows may hold the profile */
    }
  }
}

/** Find a fixture's record in a probe result. */
const find = (r, source, encoding) => r.fixtures.find((f) => f.source === source && f.encoding === encoding);

copyFileSync(FIXTURES_JS, BACKUP);
const server = await startCollector();
const controls = [];

try {
  // ---- 1. corrupted bytes ------------------------------------------------------------
  {
    const p = readPayload();
    const target = p.fixtures.find((f) => f.encoding === "capture-jpeg");
    const raw = Buffer.from(p.blobs[target.file], "base64");
    // A byte well inside the entropy-coded data, so the file still parses as a JPEG and the
    // ONLY thing that has changed is that it is no longer the file the reference read.
    raw[Math.floor(raw.length * 0.6)] ^= 0xff;
    p.blobs[target.file] = raw.toString("base64");
    writePayload(p);
    const r = await runProbe();
    const rec = find(r, target.source, target.encoding);
    controls.push({
      control: "corrupted-bytes",
      broke: `one byte of ${target.file} flipped`,
      guard: "in-browser SHA-256 of the encoded bytes",
      fired: rec?.encodedSha256Matches === false,
      observed: { encodedSha256Matches: rec?.encodedSha256Matches, skipped: rec?.skipped ?? null },
      // A corrupted file is MISSING evidence, not a wrong browser. The aggregator must
      // classify it UNKNOWN, and never REJECT.
      wouldClassifyAs: rec?.encodedSha256Matches === false ? "UNKNOWN" : "(guard did not fire)",
    });
    copyFileSync(BACKUP, FIXTURES_JS);
  }

  // ---- 2. mislabelled type -----------------------------------------------------------
  {
    const p = readPayload();
    const target = p.fixtures.find((f) => f.encoding === "capture-png");
    target.mime = "image/jpeg"; // the bytes are still a PNG
    writePayload(p);
    const r = await runProbe();
    const rec = find(r, target.source, target.encoding);
    controls.push({
      control: "mislabelled-type",
      broke: `${target.file} relabelled as image/jpeg while still being a PNG`,
      guard: "magic bytes checked against the declared MIME",
      fired: rec?.magicMatchesDeclaredMime === false,
      observed: { magic: rec?.magic, magicMatchesDeclaredMime: rec?.magicMatchesDeclaredMime, conformant: rec?.conformant },
      wouldClassifyAs: rec?.conformant === false ? "REJECT" : "(guard did not fire)",
    });
    copyFileSync(BACKUP, FIXTURES_JS);
  }

  // ---- 3. swapped reference ----------------------------------------------------------
  //
  // The one that tests the MEASUREMENT rather than an integrity check.
  {
    const p = readPayload();
    const a = p.fixtures.find((f) => f.page === "controls" && f.encoding === "capture-jpeg");
    const b = p.fixtures.find((f) => f.page === "realistic-ui" && f.encoding === "capture-jpeg");
    // Same dimensions (both 1264x800), so the comparison cannot escape through a length
    // mismatch — it has to actually look at the pixels.
    a.refDecoded = b.refDecoded;
    a.digests = { ...a.digests, decoded: b.digests.decoded };
    writePayload(p);
    const r = await runProbe();
    const rec = find(r, a.source, a.encoding);
    const d = rec?.variants?.default?.decoded;
    controls.push({
      control: "swapped-reference",
      broke: `${a.page}'s reference decode replaced with ${b.page}'s (identical dimensions)`,
      guard: "decoded-pixel comparison against the reference dump",
      fired: rec?.conformant === false && d?.identical === false,
      observed: {
        conformant: rec?.conformant,
        decodedDigestMatches: rec?.variants?.default?.decodedDigestMatches,
        maxAbs: d?.maxAbs,
        meanAbs: d?.meanAbs,
        lengthMismatch: d?.lengthMismatch ?? false,
      },
      wouldClassifyAs: rec?.conformant === false ? "REJECT" : "(guard did not fire)",
    });
    copyFileSync(BACKUP, FIXTURES_JS);
  }
} finally {
  copyFileSync(BACKUP, FIXTURES_JS);
  rmSync(BACKUP, { force: true });
  server.close();
}

const out = {
  experiment: "W1-QG03b2a-chromium-jpeg-capture",
  purpose: "evidence that the conformance harness reports a difference when one exists",
  ranAt: new Date().toISOString(),
  allFired: controls.every((c) => c.fired),
  controls,
};
writeFileSync(join(HERE, "..", "negative-controls.json"), JSON.stringify(out, null, 2));

for (const c of controls) {
  console.log(`${c.fired ? "FIRED " : "SILENT"}  ${c.control.padEnd(20)} ${c.guard}`);
  console.log(`         ${JSON.stringify(c.observed)}`);
}
console.log(`\nall controls fired: ${out.allFired}`);
process.exit(out.allFired ? 0 : 1);
