/**
 * W-1 arm A — how much of the precision / grounding problem is recoverable in
 * POST-PROCESSING alone, at the frozen operating point 0.55, on the DEV split.
 *
 *   node artifacts/experiments/W1-detector-precision-scale/harness/run-arm-a.mjs
 *
 * One inference pass per sample. The raw output is then decoded FOUR pre-registered ways
 * (design.md §5) and each decode is scored by the frozen evaluator. Every difference
 * between variants is therefore the decode rule and nothing else: same weights, same
 * pixels, same tensor, same raw logits, same operating point.
 *
 * DISCIPLINE, enforced not intended:
 *   - the dataset is REGENERATED by the unchanged tools/dataset/build-dataset.mjs and its
 *     hash must equal the pinned 4bbc57de, or this script stops;
 *   - only `split === "dev"` samples reach inference, evaluation or a log. The consumed
 *     held-out test split stays closed;
 *   - V0 is computed by BOTH the shipped decodeHeadOutput and the harness replica, and the
 *     two must be identical, or this script stops;
 *   - PROVISIONAL_THRESHOLDS is asserted, never written;
 *   - nothing is written under artifacts/datasets, artifacts/gates or artifacts/models.
 *
 * No threshold is swept. No weight is touched. Nothing here can close adoption item 11.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { hostname } from "node:os";
import {
  DEVSET, EXPERIMENT, INPUT_DIMS, MODEL, OPERATING_POINT, OUTPUT_DIMS, SHIPPED, VARIANTS,
  assertDevOnly, assertDevsetIdentity, assertModelIdentity, assertOrtVersion,
  assertShippedConstants, assertTensor, assertWritablePath, clippingCeiling, decodeVariant,
  quantiles, sameDetections, sha256Hex, taxonomy,
} from "./w1-guards.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const EXP = join(HERE, "..");
const ROOT = join(HERE, "..", "..", "..", "..");
const GEN = join(HERE, "generated", "devset");
const LOGS = join(EXP, "logs");
const refuse = (m) => { console.error(`REFUSING: ${m}`); process.exit(2); };
const num = (f) => (typeof f === "number" ? f : f && typeof f.value === "number" ? f.value : Number.NaN);
const r6 = (v) => (Number.isFinite(v) ? Math.round(v * 1e6) / 1e6 : v);

for (const p of ["packages/perception/dist/src/index.js", "packages/evaluation/dist/src/index.js"]) {
  if (!existsSync(join(ROOT, p))) refuse(`missing ${p} (run: npm run typecheck)`);
}
const P = await import(pathToFileURL(join(ROOT, "packages/perception/dist/src/index.js")).href);
const E = await import(pathToFileURL(join(ROOT, "packages/evaluation/dist/src/index.js")).href);

let shipped;
try { shipped = assertShippedConstants(P); } catch (e) { refuse(e.message); }

// ── the dataset must BE the pinned dev split ───────────────────────────────────────────
const mPath = join(GEN, "manifest.json");
const dPath = join(GEN, "decode.json");
if (!existsSync(mPath)) refuse(`no manifest at ${mPath} — run: node tools/dataset/build-dataset.mjs --out=${GEN}`);
if (!existsSync(dPath)) refuse(`no decode.json at ${dPath} — run: python ${join(HERE, "decode-w1-png.py")}`);
const ds = JSON.parse(readFileSync(mPath, "utf8"));
E.validateDataset(ds);
let dev;
try { dev = assertDevsetIdentity(ds, DEVSET); } catch (e) { refuse(e.message); }
try { assertDevOnly(dev, "arm A"); } catch (e) { refuse(e.message); }
const decode = JSON.parse(readFileSync(dPath, "utf8"));
if (decode.datasetHash !== ds.hash) refuse(`decode.json is for dataset ${decode.datasetHash}, manifest is ${ds.hash}`);

const modelBytes = readFileSync(join(ROOT, MODEL.path));
try { assertModelIdentity(modelBytes); } catch (e) { refuse(e.message); }

const ortMod = await import("onnxruntime-web");
const ort = ortMod.default ?? ortMod;
ort.env.wasm.numThreads = 1;
ort.env.wasm.proxy = false;
ort.env.logLevel = "error";
try { assertOrtVersion(ort.env.versions && ort.env.versions.web, "onnxruntime-web in Node"); } catch (e) { refuse(e.message); }
const session = await ort.InferenceSession.create(modelBytes, { executionProviders: ["wasm"], graphOptimizationLevel: "all" });

assertWritablePath(ROOT, LOGS);
mkdirSync(LOGS, { recursive: true });

const classes = P.HEAD_CONTRACT.classes;
const perVariantPreds = new Map(VARIANTS.map((v) => [v.id, []]));
const rows = [];
let replicaChecked = 0;

for (const s of dev) {
  if (s.split !== "dev") refuse(`${s.id}: split ${s.split} reached inference`);
  const d = decode.samples.find((x) => x.id === s.id);
  if (!d) refuse(`${s.id}: no decode record`);
  const rgba = readFileSync(join(GEN, "rgba", `${s.id}.rgba`));
  if (sha256Hex(rgba) !== d.rgbaSha256) refuse(`${s.id}: RGBA digest does not match decode.json`);
  if (rgba.length !== s.captureSize.w * s.captureSize.h * 4) refuse(`${s.id}: RGBA length does not match captureSize`);

  const pre = P.preprocessToTensor({ width: s.captureSize.w, height: s.captureSize.h, rgba: new Uint8Array(rgba) }, P.HEAD_CONTRACT);
  try { assertTensor(INPUT_DIMS, pre.tensor, INPUT_DIMS, `${s.id} input`); } catch (e) { refuse(e.message); }

  const res = await session.run({ [session.inputNames[0]]: new ort.Tensor("float32", pre.tensor, INPUT_DIMS) });
  const o = res[session.outputNames[0]];
  const data = o.data instanceof Float32Array ? o.data : Float32Array.from(o.data);
  try { assertTensor(Array.from(o.dims), data, OUTPUT_DIMS, `${s.id} output`); } catch (e) { refuse(e.message); }
  const out = { data, dims: Array.from(o.dims) };

  // the shipped decode, and the replica configured as V0 — they must agree exactly
  const shippedDec = P.decodeHeadOutput(out);
  if (!shippedDec.ok) refuse(`${s.id}: the shipped decode refused with ${shippedDec.code}`);
  const v0 = decodeVariant(out, classes, VARIANTS[0]);
  if (!sameDetections(shippedDec.value, v0)) {
    refuse(`${s.id}: the V0 replica does not reproduce the shipped decode — a variant comparison with a wrong baseline measures nothing`);
  }
  replicaChecked += 1;

  const cap = { w: s.captureSize.w, h: s.captureSize.h };
  const lb = P.computeLetterbox(cap, P.HEAD_CONTRACT.inputSize);
  const cssScale = s.viewportCss.w / cap.w;

  const counts = {};
  for (const variant of VARIANTS) {
    const dets = variant.id === "V0" ? shippedDec.value : decodeVariant(out, classes, variant);
    const projected = P.projectToCapture(dets, lb);
    const preds = projected
      .map((x) => ({
        sampleId: s.id,
        cls: x.label,
        box: { x: x.box.x * cssScale, y: x.box.y * cssScale, w: x.box.w * cssScale, h: x.box.h * cssScale },
        confidence: x.score,
        frameId: s.id,
        modelId: MODEL.modelId,
        revision: MODEL.revision,
      }))
      .filter((p) => p.confidence >= OPERATING_POINT);
    perVariantPreds.get(variant.id).push(...preds);
    counts[variant.id] = { beforeNmsProjection: dets.length, atOperatingPoint: preds.length };
  }

  rows.push({
    id: s.id,
    split: s.split,
    seed: s.provenance.seed,
    viewportCss: s.viewportCss,
    captureSize: s.captureSize,
    evaluatableAnnotations: s.annotations.filter((a) => a.visibility !== "OFFSCREEN").length,
    pngSha256: d.pngSha256,
    rgbaSha256: d.rgbaSha256,
    tensorSha256: sha256Hex(Buffer.from(pre.tensor.buffer, pre.tensor.byteOffset, pre.tensor.byteLength)),
    outputSha256: sha256Hex(Buffer.from(data.buffer, data.byteOffset, data.byteLength)),
    counts,
  });
}

// ── score every variant with the FROZEN evaluator ──────────────────────────────────────
const ceiling = clippingCeiling(dev);
const bySample = new Map(dev.map((s) => [s.id, s]));
const results = [];
for (const variant of VARIANTS) {
  const preds = perVariantPreds.get(variant.id);
  const ev = E.evaluate(ds, preds, "dev", {
    datasetName: ds.name,
    datasetVersion: ds.version,
    datasetHash: ds.hash,
    split: "dev",
    modelId: MODEL.modelId,
    modelRevision: MODEL.revision,
    backend: "wasm",
    browser: `node ${process.version}`,
    preprocessing: "shipped preprocessToTensor: rasterLetterbox to 640 square, BILINEAR, centred pad 114/255, RGB, /255",
    evaluatedAt: new Date().toISOString(),
  });
  const predsBySample = new Map();
  for (const p of preds) {
    if (!bySample.has(p.sampleId)) refuse(`prediction for unknown or non-dev sample ${p.sampleId}`);
    if (!predsBySample.has(p.sampleId)) predsBySample.set(p.sampleId, []);
    predsBySample.get(p.sampleId).push(p);
  }
  const tx = taxonomy(dev, predsBySample);
  const fpTotal = tx.fp.duplicate + tx.fp.classConfusion + tx.fp.localization + tx.fp.spurious;
  results.push({
    variant: variant.id,
    label: variant.label,
    operatingPoint: OPERATING_POINT,
    mAP50: r6(num(ev.mAP50)),
    elementRecall: r6(num(ev.elementRecall)),
    recallCeilingRelative: r6(num(ev.elementRecall) / ceiling.ceiling),
    groundingAccuracy: r6(num(ev.groundingAccuracy)),
    predictions: preds.length,
    predictionsPerScreen: r6(preds.length / dev.length),
    matched: tx.matchedGt,
    groundTruth: tx.totalGt,
    falsePositives: fpTotal,
    falsePositiveTaxonomy: tx.fp,
    falsePositiveShare: fpTotal
      ? Object.fromEntries(Object.entries(tx.fp).map(([k, v]) => [k, r6(v / fpTotal)]))
      : null,
    falseNegativeTaxonomy: tx.fn,
    topConfusions: Object.fromEntries(Object.entries(tx.confusion).sort((a, b) => b[1] - a[1]).slice(0, 8)),
    matchedIou: tx.matchedIou.length ? Object.fromEntries(Object.entries(quantiles(tx.matchedIou)).map(([k, v]) => [k, r6(v)])) : null,
    normalisedDisplacement: tx.normDisp.length ? Object.fromEntries(Object.entries(quantiles(tx.normDisp)).map(([k, v]) => [k, r6(v)])) : null,
    perClass: ev.perClass.map((c) => ({ cls: c.cls, gt: c.groundTruth, pred: c.predictions, tp: c.truePositives, ap50: r6(num(c.ap50)), recall: r6(num(c.recall)), precision: r6(num(c.precision)) })),
  });
}

const v0 = results[0];
const deltas = results.slice(1).map((r) => ({
  variant: r.variant,
  label: r.label,
  dGrounding: r6(r.groundingAccuracy - v0.groundingAccuracy),
  dRecall: r6(r.elementRecall - v0.elementRecall),
  dMAP50: r6(r.mAP50 - v0.mAP50),
  dPredictionsPerScreen: r6(r.predictionsPerScreen - v0.predictionsPerScreen),
  dMatched: r.matched - v0.matched,
  dFalsePositives: r.falsePositives - v0.falsePositives,
  dTaxonomy: Object.fromEntries(Object.keys(v0.falsePositiveTaxonomy).map((k) => [k, r.falsePositiveTaxonomy[k] - v0.falsePositiveTaxonomy[k]])),
}));

const log = {
  experiment: EXPERIMENT,
  arm: "A — post-processing, DEV only, no retrain, no shipped-code change",
  runAt: new Date().toISOString(),
  machine: { hostname: hostname(), node: process.version },
  model: { ...MODEL, sha256Verified: sha256Hex(modelBytes) },
  ort: { version: ort.env.versions && ort.env.versions.web, backend: "wasm", numThreads: 1, proxy: false },
  shippedConstants: { ...shipped },
  shippedConstantsExpected: SHIPPED,
  dataset: { name: ds.name, version: ds.version, hash: ds.hash, pinnedHash: DEVSET.hash, identityVerified: ds.hash === DEVSET.hash, split: "dev", samples: dev.length },
  testSplitOpened: false,
  replicaMatchesShippedDecode: { samples: replicaChecked, allIdentical: true },
  clippingCeiling: { ...ceiling, ceiling: r6(ceiling.ceiling) },
  variants: VARIANTS,
  results,
  deltasAgainstV0: deltas,
  samples: rows,
  notClaimed: [
    "SYNTHETIC evidence. This cannot close adoption item 11.",
    "No variant is adopted; the shipped decode and PROVISIONAL_THRESHOLDS are unchanged.",
    "No threshold was swept, on any split. The consumed held-out test split was not opened.",
    "No definition of 'substantial' improvement is set here — the absolute deltas go to the owner.",
  ],
};
writeFileSync(join(LOGS, "arm-a.json"), `${JSON.stringify(log, null, 1)}\n`);

console.log(`\narm A — dev ${dev.length} samples, dataset ${ds.name}@${ds.hash} (pinned ${DEVSET.hash}: ${ds.hash === DEVSET.hash ? "MATCH" : "MISMATCH"})`);
console.log(`V0 replica reproduced the shipped decode on ${replicaChecked}/${dev.length} samples`);
console.log(`clipped ceiling ${r6(ceiling.ceiling)} (${ceiling.unreachable}/${ceiling.evaluatable} unreachable)\n`);
for (const r of results) {
  console.log(`${r.variant}  mAP ${r.mAP50.toFixed(4)}  recall ${r.elementRecall.toFixed(4)}  grounding ${r.groundingAccuracy.toFixed(4)}  preds/screen ${r.predictionsPerScreen.toFixed(2)}  FP ${r.falsePositives}  dup ${r.falsePositiveTaxonomy.duplicate} cc ${r.falsePositiveTaxonomy.classConfusion} loc ${r.falsePositiveTaxonomy.localization} spur ${r.falsePositiveTaxonomy.spurious}`);
}
console.log("");
for (const d of deltas) {
  console.log(`${d.variant} vs V0  grounding ${d.dGrounding >= 0 ? "+" : ""}${d.dGrounding}  recall ${d.dRecall >= 0 ? "+" : ""}${d.dRecall}  preds/screen ${d.dPredictionsPerScreen}  dup ${d.dTaxonomy.duplicate}`);
}
console.log(`\nwrote ${join(LOGS, "arm-a.json")}`);
