/**
 * Assemble the QG-03a-B3-1 MV3 extension (Chromium).
 *
 *   node artifacts/experiments/W1-QG03a-B3-1-mv3-extension-backends/harness/build-b3-extension.mjs
 *
 * Prerequisites (refused, never worked around): `npm run typecheck` (compiles
 * packages/{perception,security} to dist/), `npm ci` (onnxruntime-web 1.29.0), and the model at
 * artifacts/models/t1-ui-head/t1-ui-head.onnx with the documented size and SHA-256.
 *
 * Adapted from W1-QG03b2a's build-qg03b2a-extension.mjs:
 *   - MV3 service worker -> chrome.offscreen document. ORT cannot run in a service worker
 *     (dynamic import() is forbidden there, S-03), which is why the offscreen document exists.
 *   - the offscreen document can also start a DEDICATED WORKER (b3-worker.js), the realm
 *     apps/extension/entrypoints/ortRuntime.ts names as where inference runs.
 *   - the shipped compiled packages go in VERBATIM. No bundler.
 *   - the ORT files are copied from node_modules and each is checked against ORT_PIN here, and
 *     the artifact is verified again in the realm by installVerifiedOrtRuntime.
 *   - the model and the 20 PNGs are INLINED as base64, so neither is fetched at all.
 *   - the CSP is built by the SHIPPED buildExtensionPagesCsp, with connect-src pinned to the
 *     loopback collector, the harness's only destination.
 *
 * Nothing here is product code, and no manifest here is a product manifest.
 */
import { copyFileSync, cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { MODEL, ORT_VERSION, ORT_ARTIFACT, assertModelIdentity, assertOrtVersion, assertFixtureBytes, selectPngFixtures, sha256Hex } from "./b3-guards.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..", "..", "..", "..");
const OUT = join(HERE, "ext-chrome");
const QG = join(ROOT, "artifacts/experiments/W1-QG03b2a-chromium-jpeg-capture");
const ORT_DIST = join(ROOT, "node_modules", "onnxruntime-web", "dist");
export const PORT = 8971;
const COLLECTOR = `http://127.0.0.1:${PORT}`;

function refuse(msg) {
  console.error(`REFUSING TO BUILD: ${msg}`);
  process.exit(2);
}
for (const p of ["packages/perception/dist/src/index.js", "packages/security/dist/src/index.js"]) {
  if (!existsSync(join(ROOT, p))) refuse(`missing ${p} (run: npm run typecheck)`);
}

const ortPackageVersion = JSON.parse(readFileSync(join(ROOT, "node_modules/onnxruntime-web/package.json"), "utf8")).version;
try { assertOrtVersion(ortPackageVersion, "node_modules/onnxruntime-web"); } catch (e) { refuse(e.message); }

const SEC = await import(pathToFileURL(join(ROOT, "packages/security/dist/src/index.js")).href);
const pin = SEC.ORT_PIN;
if (pin.version !== ORT_VERSION || pin.artifact.sha256 !== ORT_ARTIFACT.sha256) refuse("ORT_PIN in packages/security does not match the B3-1 guard constants");
const ORT_FILES = ["ort.all.min.js", "ort-wasm-simd-threaded.mjs", "ort-wasm-simd-threaded.wasm", "ort-wasm-simd-threaded.jsep.mjs", "ort-wasm-simd-threaded.jsep.wasm"];
const ortHashes = {};
for (const f of ORT_FILES) {
  const p = join(ORT_DIST, f);
  if (!existsSync(p)) refuse(`missing ${p} (run: npm ci)`);
  ortHashes[f] = sha256Hex(readFileSync(p));
}
for (const k of ["bundle", "artifact", "glue"]) {
  if (ortHashes[pin[k].name] !== pin[k].sha256) refuse(`${pin[k].name} does not match ORT_PIN.${k}`);
}

let modelBytes;
try {
  modelBytes = readFileSync(join(ROOT, MODEL.path));
  assertModelIdentity(modelBytes);
} catch (e) {
  refuse(`model: ${e.message}`);
}

const fixtures = selectPngFixtures(JSON.parse(readFileSync(join(QG, "fixtures.json"), "utf8")));
const blobs = {};
for (const f of fixtures) {
  const bytes = readFileSync(join(QG, "harness", "captured", f.file));
  try { assertFixtureBytes(f, bytes); } catch (e) { refuse(e.message); }
  blobs[f.file] = bytes.toString("base64");
}

const CSP = SEC.buildExtensionPagesCsp(COLLECTOR);
rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
for (const f of ORT_FILES) copyFileSync(join(ORT_DIST, f), join(OUT, f));
cpSync(join(ROOT, "packages/perception/dist/src"), join(OUT, "perception"), { recursive: true });
cpSync(join(ROOT, "packages/security/dist/src"), join(OUT, "security"), { recursive: true });
for (const sub of ["perception", "security", "security/generated"]) {
  const d = join(OUT, sub);
  if (!existsSync(d)) continue;
  for (const f of readdirSync(d)) if (f.endsWith(".d.ts")) rmSync(join(d, f));
}
const HARNESS_FILES = ["b3-instrument.js", "b3-probe.js"];
for (const f of HARNESS_FILES) copyFileSync(join(HERE, f), join(OUT, f));

writeFileSync(
  join(OUT, "b3-fixtures.js"),
  `// GENERATED by build-b3-extension.mjs; do not edit.\nglobalThis.B3_FIXTURES = ${JSON.stringify({
    model: { sha256: MODEL.sha256, bytes: MODEL.bytes, b64: modelBytes.toString("base64") },
    fixtures: fixtures.map((f) => ({ name: f.name, file: f.file, encodedSha256: f.encodedSha256 })),
    blobs,
  })};\n`
);

writeFileSync(
  join(OUT, "manifest.json"),
  JSON.stringify(
    {
      manifest_version: 3,
      name: "PratiBimb QG-03a-B3-1 real-model backends (Chrome)",
      version: "1.0.0",
      description: "Throwaway harness. Runs the exact T1 artifact through ADR-0001's pinned ORT path in the offscreen document or its worker.",
      minimum_chrome_version: "116",
      background: { service_worker: "background.js" },
      permissions: ["offscreen"],
      host_permissions: [`${COLLECTOR}/*`],
      content_security_policy: { extension_pages: CSP },
    },
    null,
    2
  )
);

// ORDER IS LOAD-BEARING: the instrument wraps GPUQueue.submit and requestAdapter before ORT exists.
writeFileSync(
  join(OUT, "offscreen.html"),
  '<!doctype html><html><head><meta charset="utf-8"><title>qg03a-b3-1</title>' +
    '<script src="b3-instrument.js"></script><script src="ort.all.min.js"></script>' +
    '<script src="b3-fixtures.js"></script><script src="b3-probe.js"></script><script src="offscreen.js"></script>' +
    "</head><body></body></html>"
);

writeFileSync(
  join(OUT, "b3-worker.js"),
  [
    "// Dedicated worker created by the offscreen document. Instrument FIRST, then ORT.",
    'importScripts("b3-instrument.js", "ort.all.min.js", "b3-fixtures.js", "b3-probe.js");',
    "self.onmessage = async (e) => {",
    "  let r;",
    "  try { r = await self.runB3Probe(e.data); }",
    '  catch (err) { r = { error: "worker: " + String((err && err.message) || err).slice(0, 400), rows: [] }; }',
    "  self.postMessage(r);",
    "};",
  ].join("\n")
);

writeFileSync(
  join(OUT, "offscreen.js"),
  [
    "chrome.runtime.onMessage.addListener((msg) => {",
    '  if (!msg || msg.type !== "b3-go") return;',
    "  (async () => {",
    "    const cfg = msg.config;",
    "    let result;",
    "    try {",
    '      if (cfg.realm === "document") result = await globalThis.runB3Probe(cfg);',
    '      else if (cfg.realm === "worker") result = await new Promise((resolve, reject) => {',
    '        const w = new Worker("b3-worker.js");',
    "        w.onmessage = (e) => { resolve(e.data); w.terminate(); };",
    '        w.onerror = (e) => reject(new Error("worker error: " + (e.message || "unknown")));',
    "        w.postMessage(cfg);",
    "      });",
    '      else throw new Error("unknown realm " + cfg.realm);',
    "    } catch (e) {",
    '      result = { error: "offscreen host: " + String((e && e.message) || e).slice(0, 400), realmRequested: cfg.realm, rows: [] };',
    "    }",
    "    let posted = false;",
    "    try {",
    '      const r = await fetch(cfg.collector + "/result?cell=" + encodeURIComponent(cfg.cell), { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify(result) });',
    "      posted = r.ok;",
    "    } catch (e) { /* the runner times out and records the absence */ }",
    '    chrome.runtime.sendMessage({ type: "b3-done", posted: posted, error: result.error || null });',
    "  })();",
    "});",
  ].join("\n")
);

writeFileSync(
  join(OUT, "background.js"),
  [
    "// MV3 service worker. Creates and drives the offscreen document; it does NOT run ORT.",
    `const COLLECTOR = ${JSON.stringify(COLLECTOR)};`,
    "async function offscreenContexts() {",
    '  const c = await chrome.runtime.getContexts({ contextTypes: ["OFFSCREEN_DOCUMENT"] });',
    "  return c.map((x) => ({ contextType: x.contextType, documentUrl: x.documentUrl, documentOrigin: x.documentOrigin || null }));",
    "}",
    "globalThis.__b3_run = async function (cfg) {",
    '  const existing = await chrome.runtime.getContexts({ contextTypes: ["OFFSCREEN_DOCUMENT"] });',
    '  if (!existing.length) await chrome.offscreen.createDocument({ url: "offscreen.html", reasons: ["WORKERS"], justification: "QG-03a-B3-1 harness" });',
    "  const report = { extensionId: chrome.runtime.id, serviceWorkerUrl: self.location.href, offscreenContexts: await offscreenContexts(), userAgent: navigator.userAgent };",
    '  try { report.fullVersionList = (await navigator.userAgentData.getHighEntropyValues(["fullVersionList"])).fullVersionList; } catch (e) { report.fullVersionListError = String(e).slice(0, 200); }',
    '  await fetch(COLLECTOR + "/sw-report", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify(report) });',
    "  return await new Promise((resolve) => {",
    '    const t = setTimeout(() => resolve({ posted: false, error: "offscreen timeout" }), 850000);',
    "    chrome.runtime.onMessage.addListener(function h(m) {",
    '      if (m && m.type === "b3-done") { clearTimeout(t); chrome.runtime.onMessage.removeListener(h); resolve(m); }',
    "    });",
    '    chrome.runtime.sendMessage({ type: "b3-go", config: cfg }).catch(() => {});',
    "  });",
    "};",
  ].join("\n")
);

const buildManifest = {
  experiment: "W1-QG03a-B3-1-mv3-extension-backends",
  builtAt: new Date().toISOString(),
  collector: COLLECTOR,
  csp: CSP,
  ortPackageVersion,
  ortFiles: ortHashes,
  model: { path: MODEL.path, bytes: MODEL.bytes, sha256: MODEL.sha256 },
  fixtures: fixtures.map((f) => ({ name: f.name, file: f.file, encodedSha256: f.encodedSha256 })),
  harnessFiles: Object.fromEntries(HARNESS_FILES.map((f) => [f, sha256Hex(readFileSync(join(HERE, f)))])),
};
writeFileSync(join(OUT, "build-manifest.json"), JSON.stringify(buildManifest, null, 1));

console.log("built ext-chrome");
console.log(`  CSP (from the shipped builder): ${CSP}`);
console.log(`  ORT ${ortPackageVersion}; artifact ${ORT_ARTIFACT.name} ${ortHashes[ORT_ARTIFACT.name].slice(0, 16)}...`);
console.log(`  model ${MODEL.bytes} bytes ${MODEL.sha256.slice(0, 16)}... inlined`);
console.log(`  fixtures ${fixtures.length} PNG, hash-checked, inlined`);
