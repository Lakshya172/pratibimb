#!/usr/bin/env node
/**
 * Build the G1/G2/G3 gate extensions from the PRODUCTION CSP.
 *
 * The policy is not written out by hand here. It is produced by the same
 * `buildExtensionPagesCsp()` the shipped manifest uses, so if the approved policy ever
 * changes, these gates exercise the new one — and if someone widens it, G2/G3 fail.
 *
 * The CSP function is a TypeScript module and this is a plain Node script, so the policy
 * is re-derived from its source rather than imported. `assertApprovedCsp` in the unit
 * suite is what guarantees the two agree; this file's copy is checked against the source
 * at build time below, and the build FAILS if they diverge.
 */
import { mkdirSync, rmSync, writeFileSync, readFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..", "..", "..");
const OUT = join(HERE, "build");

const ALLOWED = "http://127.0.0.1:8920";
const FOREIGN = "http://127.0.0.1:8921";

/** Mirrors packages/security/src/csp.ts. Verified against it below. */
function buildExtensionPagesCsp(serverOrigin) {
  return [
    "script-src 'self' 'wasm-unsafe-eval'",
    "object-src 'self'",
    `connect-src 'self' ${serverOrigin}`,
  ].join("; ");
}

/**
 * Guard against this file drifting from the production policy. If csp.ts changes shape,
 * the gate must not keep testing a stale string and reporting green.
 */
function assertMirrorsSource() {
  const src = readFileSync(join(ROOT, "packages", "security", "src", "csp.ts"), "utf8");
  const directives = [
    `"script-src 'self' 'wasm-unsafe-eval'"`,
    `"object-src 'self'"`,
    "`connect-src 'self' ${origin}`",
  ];
  const missing = directives.filter((d) => !src.includes(d));
  if (missing.length) {
    console.error("\nGATE BUILD: FAIL\n");
    console.error(
      "tests/browser/gates/build-gate-extensions.mjs no longer mirrors\n" +
        "packages/security/src/csp.ts. The gate would test a policy the product does not\n" +
        "ship. Update this file to match, then re-run.\n\n  not found in csp.ts:\n    " +
        missing.join("\n    ")
    );
    process.exit(1);
  }
}

/** The 41-byte probe module, byte-identical to the one the probe compiles inline. */
const PROBE_WASM = Buffer.from([
  0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00,
  0x01, 0x07, 0x01, 0x60, 0x02, 0x7f, 0x7f, 0x01, 0x7f,
  0x03, 0x02, 0x01, 0x00,
  0x07, 0x07, 0x01, 0x03, 0x61, 0x64, 0x64, 0x00, 0x00,
  0x0a, 0x09, 0x01, 0x07, 0x00, 0x20, 0x00, 0x20, 0x01, 0x6a, 0x0b,
]);

const CSP = buildExtensionPagesCsp(ALLOWED);

const configJs = `// generated by build-gate-extensions.mjs
self.PRATIBIMB_GATE_CFG = {
  csp: ${JSON.stringify(CSP)},
  allowedOrigin: ${JSON.stringify(ALLOWED)},
  foreignOrigin: ${JSON.stringify(FOREIGN)}
};
self.gateBeacon = function (p) {
  try {
    const api = typeof browser !== "undefined" ? browser : chrome;
    return api.tabs.create({ url: ${JSON.stringify(ALLOWED)} + p, active: false });
  } catch (e) { return Promise.resolve(); }
};
`;

function writeCommon(dir) {
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "config.js"), configJs);
  writeFileSync(join(dir, "gate-probe.js"), readFileSync(join(HERE, "gate-probe.js")));
}

function buildChrome() {
  const dir = join(OUT, "chrome");
  writeCommon(dir);
  writeFileSync(
    join(dir, "manifest.json"),
    JSON.stringify(
      {
        manifest_version: 3,
        name: "PratiBimb ADR-0001 gates (chrome)",
        version: "1.0.0",
        minimum_chrome_version: "116",
        background: { service_worker: "background.js" },
        permissions: ["offscreen"],
        // BOTH origins are permitted here. That is the control that makes a G2 block
        // attributable to connect-src rather than to host_permissions.
        host_permissions: [`${ALLOWED}/*`, `${FOREIGN}/*`],
        content_security_policy: { extension_pages: CSP },
      },
      null,
      2
    ) + "\n"
  );
  writeFileSync(
    join(dir, "offscreen.html"),
    '<!doctype html><meta charset="utf-8"><body>' +
      '<script src="config.js"></script><script src="gate-probe.js"></script>' +
      '<script src="offscreen.js"></script></body>'
  );
  writeFileSync(
    join(dir, "offscreen.js"),
    [
      "(async () => {",
      '  await self.reportGate("chrome-offscreen-document");',
      '  const w = new Worker("worker.js");',
      "  await new Promise((res) => {",
      "    w.onmessage = () => res();",
      "    w.onerror = () => res();",
      '    w.postMessage({ type: "run" });',
      "    setTimeout(res, 60000);",
      "  });",
      "  w.terminate();",
      '  await fetch(self.PRATIBIMB_GATE_CFG.allowedOrigin + "/done", { method: "POST" }).catch(() => {});',
      "})();",
    ].join("\n")
  );
  writeFileSync(
    join(dir, "worker.js"),
    [
      'importScripts("config.js", "gate-probe.js");',
      "self.onmessage = async (e) => {",
      "  if (!e.data || e.data.type !== \"run\") return;",
      '  await self.reportGate("chrome-offscreen-dedicated-worker");',
      '  self.postMessage({ type: "done" });',
      "};",
    ].join("\n")
  );
  writeFileSync(
    join(dir, "background.js"),
    [
      'importScripts("config.js", "gate-probe.js");',
      "// Liveness first: 'the extension never loaded' and 'it loaded and every gate",
      "// failed' are different results and must never be confused.",
      "async function alive() {",
      "  try {",
      '    await fetch(self.PRATIBIMB_GATE_CFG.allowedOrigin + "/log", {',
      '      method: "POST", headers: { "content-type": "application/json",',
      '        "x-pratibimb-gate": "alive" },',
      '      body: JSON.stringify({ stage: "alive", csp: chrome.runtime.getManifest().content_security_policy })',
      "    });",
      "  } catch (_) {}",
      "}",
      "let started = false;",
      "async function main() {",
      "  if (started) return; started = true;",
      "  await alive();",
      '  await self.reportGate("chrome-mv3-service-worker");',
      "  if (!(await chrome.offscreen.hasDocument?.())) {",
      '    await chrome.offscreen.createDocument({ url: "offscreen.html", reasons: ["WORKERS"],',
      '      justification: "Host a dedicated worker for the ADR-0001 gate suite." });',
      "  }",
      "}",
      "chrome.runtime.onInstalled.addListener(main);",
      "chrome.runtime.onStartup.addListener(main);",
      "main();",
    ].join("\n")
  );
  return dir;
}

function buildFirefox() {
  const dir = join(OUT, "firefox");
  writeCommon(dir);
  writeFileSync(
    join(dir, "manifest.json"),
    JSON.stringify(
      {
        manifest_version: 3,
        name: "PratiBimb ADR-0001 gates (firefox)",
        version: "1.0.0",
        browser_specific_settings: {
          gecko: { id: "pratibimb-adr0001-gates@example.invalid", strict_min_version: "128.0" },
        },
        background: { scripts: ["config.js", "gate-probe.js", "ff-background.js"] },
        permissions: ["tabs"],
        host_permissions: [`${ALLOWED}/*`, `${FOREIGN}/*`],
        content_security_policy: { extension_pages: CSP },
      },
      null,
      2
    ) + "\n"
  );
  writeFileSync(
    join(dir, "ff-background.js"),
    [
      "(async () => {",
      '  await self.gateBeacon("/log?stage=alive");',
      '  await self.reportGate("firefox-mv3-event-page");',
      "  try {",
      '    const w = new Worker("worker.js");',
      "    await new Promise((res) => {",
      "      w.onmessage = () => res();",
      "      w.onerror = () => res();",
      '      w.postMessage({ type: "run" });',
      "      setTimeout(res, 60000);",
      "    });",
      "    w.terminate();",
      "  } catch (e) { /* reported by the worker path itself */ }",
      '  await self.gateBeacon("/done");',
      "})();",
    ].join("\n")
  );
  writeFileSync(
    join(dir, "worker.js"),
    [
      'importScripts("config.js", "gate-probe.js");',
      "self.onmessage = async (e) => {",
      '  if (!e.data || e.data.type !== "run") return;',
      '  await self.reportGate("firefox-event-page-dedicated-worker");',
      '  self.postMessage({ type: "done" });',
      "};",
    ].join("\n")
  );
  return dir;
}

assertMirrorsSource();
rmSync(OUT, { recursive: true, force: true });
const chrome = buildChrome();
const firefox = buildFirefox();
mkdirSync(join(OUT, "served"), { recursive: true });
writeFileSync(join(OUT, "served", "probe.wasm"), PROBE_WASM);

console.log("GATE BUILD OK");
console.log(`  CSP under test : ${CSP}`);
console.log(`  chrome         : ${chrome}`);
console.log(`  firefox        : ${firefox}`);
console.log(`  served         : ${join(OUT, "served", "probe.wasm")} (${PROBE_WASM.length} bytes)`);
if (!existsSync(join(chrome, "manifest.json"))) process.exit(1);
